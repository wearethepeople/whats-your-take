import {
  isRouteErrorResponse,
  Links,
  Meta,
  Outlet,
  redirect,
  Scripts,
  ScrollRestoration,
} from "react-router";
import type { Route } from "./+types/root";
import { absoluteUrl, canonicalHostRedirect, isNoindexPath, SITE_NAME } from "~/lib/seo";
import "./app.css";
import publicSans400 from "@fontsource/public-sans/files/public-sans-latin-400-normal.woff2?url";
import sourceSerif600 from "@fontsource/source-serif-4/files/source-serif-4-latin-600-normal.woff2?url";

export const links: Route.LinksFunction = () =>
  [publicSans400, sourceSerif600].map((href) => ({
    rel: "preload",
    as: "font",
    type: "font/woff2",
    href,
    crossOrigin: "anonymous",
  }));

// Runs for every route, including resource routes like /sitemap.xml.
export const middleware: Route.MiddlewareFunction[] = [
  async ({ request }, next) => {
    const url = new URL(request.url);
    const target = canonicalHostRedirect(url);
    if (target) throw redirect(target, 301);

    const response = await next();
    if (response instanceof Response && isNoindexPath(url.pathname)) {
      response.headers.set("X-Robots-Tag", "noindex");
    }
    return response;
  },
];

export function Layout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en">
      <head>
        <meta charSet="utf-8" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        {/* favicon.ico is a 32px PNG; Google wants a favicon sized in multiples
            of 48px, so the 192px icon is offered alongside it. */}
        <link rel="icon" href="/favicon.ico" type="image/png" sizes="32x32" />
        <link rel="icon" href="/android-chrome-192x192.png" type="image/png" sizes="192x192" />
        <link rel="apple-touch-icon" href="/apple-touch-icon.png" />
        <link rel="manifest" href="/manifest.json" />
        <meta name="theme-color" content="#ece5dc" />
        {/* Share card: the poster lockup, generated by other/og-image.mjs.
            Title and description come from each route's meta(). */}
        <meta property="og:type" content="website" />
        <meta property="og:site_name" content={SITE_NAME} />
        <meta property="og:image" content={absoluteUrl("/og.png")} />
        <meta property="og:image:width" content="1200" />
        <meta property="og:image:height" content="630" />
        <meta property="og:image:alt" content="What’s Your Take? A civic mirror project." />
        <meta name="twitter:card" content="summary_large_image" />
        <Meta />
        <Links />
      </head>
      <body>
        {children}
        <ScrollRestoration />
        <Scripts />
      </body>
    </html>
  );
}

export default function App() {
  return <Outlet />;
}

export function ErrorBoundary({ error }: Route.ErrorBoundaryProps) {
  let message = "Something went wrong";
  let details = "Please try again.";

  if (isRouteErrorResponse(error)) {
    message = error.status === 404 ? "Not found" : "Error";
    details = error.status === 404 ? "That page doesn’t exist." : details;
  }

  return (
    <main className="container">
      <h1>{message}</h1>
      <p>{details}</p>
    </main>
  );
}
